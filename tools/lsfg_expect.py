#!/usr/bin/env python3
"""The descriptor bindings the lsfg-vk framegen expects of each shader (third_party/lsfg-vk-android/framegen/v3.1*_src/
shaders/*.cpp: getShader(device, "<name>", {{count, type}, ...})), as a C++ table for the extractor's last check
(android/totkrecompandroid/app/src/main/cpp/lsfg_expect.inc). Regenerate after moving the submodule:
  tools/lsfg_expect.py > android/totkrecompandroid/app/src/main/cpp/lsfg_expect.inc
"""
import glob
import os
import re
import subprocess

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "third_party", "lsfg-vk-android")
CALL = re.compile(r'getShader\(\s*vk\.device\s*,\s*"([^"]+)"\s*,\s*\{(.*?)\}\s*\)', re.S)
PAIR = re.compile(r"\{\s*(\d+)\s*,\s*VK_DESCRIPTOR_TYPE_([A-Z_]+)\s*\}")
KIND = {"UNIFORM_BUFFER": 0, "SAMPLER": 1, "SAMPLED_IMAGE": 2, "STORAGE_IMAGE": 3}

rows = {}
for variant, prefix in (("v3.1_src", ""), ("v3.1p_src", "p_")):
    for path in sorted(glob.glob(os.path.join(ROOT, "framegen", variant, "shaders", "*.cpp"))):
        src = open(path).read()
        for m in CALL.finditer(src):
            counts = [0, 0, 0, 0]
            for n, kind in PAIR.findall(m.group(2)):
                counts[KIND[kind]] += int(n)
            name = m.group(1)
            if prefix and not name.startswith(prefix):
                name = prefix + name
            rows[name] = counts
commit = subprocess.run(["git", "-C", ROOT, "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
print("// Generated by tools/lsfg_expect.py from lsfg-vk-android %s (MIT): the bindings framegen gives each shader -" % commit[:12])
print("// uniform buffers, samplers, sampled images, storage images.")
for name in sorted(rows):
    c = rows[name]
    print('{"%s", {%d, %d, %d, %d}},' % (name, c[0], c[1], c[2], c[3]))
